"""Fit near-length rewrites using only equivalent phrases, never filler or truncation."""
import re
import dm_variants

GROUPS=[
 ('do not',"don't"),('cannot',"can't",'can not'),('they are',"they're"),
 ('it is',"it's"),('he is',"he's"),('she is',"she's"),('we are',"we're"),
 ('you are',"you're"),('there is',"there's"),('that is',"that's"),
 ('they have',"they've"),('we have',"we've"),('has not',"hasn't"),
 ('have not',"haven't"),('will not',"won't"),('is not',"isn't"),
 ('are not',"aren't"),('does not',"doesn't"),('did not',"didn't"),
 ('in order to','to'),('right now','now'),('burial expenses','burial costs'),
 ('funeral expenses','funeral costs'),('this family','the family'),
 ('his parents','his mother and father'),('their little son','their son'),
 ('please help this family','please support this family'),('and','&'),
]
OPTIONS={phrase:group for group in GROUPS for phrase in group}
PATTERN=re.compile(r'(?<!\w)(?:'+ '|'.join(re.escape(p) for p in sorted(OPTIONS,key=len,reverse=True))+r')(?!\w)',re.I)
def protected(line):return bool(re.search(r'(?i)easypaisa|jazzcash|account|03097458815|wajdan',line))
def match_case(value,example):
 return value.upper() if example.isupper() else value[0].upper()+value[1:] if example[:1].isupper() else value

def fit_length(source,text):
 if not isinstance(text,str):return None
 text=text.replace('\r\n','\n').strip();original=source.split('\n');lines=text.split('\n')
 if len(lines)!=len(original):return None
 # Account information is copied from the source, never regenerated by the model.
 lines=[s if protected(s) else t for s,t in zip(original,lines)];text='\n'.join(lines)
 if dm_variants._shape(source)!=dm_variants._shape(text) or dm_variants._numbers(source)!=dm_variants._numbers(text) or dm_variants._emojis(source)!=dm_variants._emojis(text):return None
 target=len(source)-len(text)
 if abs(target)>max(80,int(len(source)*.15)):return None
 parts=[];choices=[]
 for line in lines:
  if protected(line):parts.append(line+'\n');continue
  last=0
  for match in PATTERN.finditer(line):
   parts.append(line[last:match.start()]);parts.append(None)
   word=match.group();opts=[word]+[match_case(p,word) for p in OPTIONS[word.lower()] if p!=word.lower()]
   choices.append(opts);last=match.end()
  parts.append(line[last:]+'\n')
 # Dynamic programming considers each non-overlapping phrase once. No loops of
 # repeated edits, padding, number changes or invented factual sentences.
 states={0:[]}
 for opts in choices:
  nxt={}
  for delta,path in states.items():
   for option in opts:
    size=delta+len(option)-len(opts[0])
    if abs(size)<=max(120,abs(target)+80) and size not in nxt:nxt[size]=path+[option]
  states=nxt
 if target not in states:return None
 values=iter(states[target]);result=''.join(next(values) if p is None else p for p in parts)[:-1]
 return result if len(result)==len(source) and result!=source else None
