"""Builds docs/DEPENDENCY_MAP.md from the code itself: module imports, HTTP routes, background threads,
persisted keys/files and which browser files call which endpoints. Run: python scripts/dependency_map.py"""

import ast, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "DEPENDENCY_MAP.md"
PY = sorted(p for p in ROOT.glob("*.py"))
NAMES = {p.stem for p in PY}


def imports(path):
    found = set()
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Import):
            found |= {a.name.split(".")[0] for a in node.names}
        elif isinstance(node, ast.ImportFrom) and node.module:
            found.add(node.module.split(".")[0])
    return sorted((found & NAMES) - {path.stem})


def routes(text):
    out = {"GET": set(), "POST": set()}
    method = None
    for line in text.splitlines():
        if re.match(r"\s+def _get\(", line):
            method = "GET"
        elif re.match(r"\s+def _post\(", line):
            method = "POST"
        elif re.match(r"\s+def \w+\(", line) and method:
            method = None if not line.strip().startswith("def reply") else method
        if method:
            for m in re.finditer(r'self\.path (?:==|\.startswith\() ?\(?"(/[\w/\-.]*)"', line):
                out[method].add(m.group(1))
            for m in re.finditer(r"self\.path in \(([^)]*)\)", line):
                out[method] |= set(re.findall(r'"(/[\w/\-.]*)"', m.group(1)))
    return out


def threads(path):
    text = path.read_text(encoding="utf-8")
    return sorted(set(re.findall(r"Thread\(\s*target=(?:self\.)?([\w.]+)", text)))


def keys(path):
    text = path.read_text(encoding="utf-8")
    ks = set(re.findall(r'STORE\.(?:get|put|put_retry|claim|seed)\(\s*"([\w_]+)"', text))
    ks |= set(re.findall(r'store\.(?:get|put|put_retry)\(\s*"([\w_]+)"', text))
    ks |= set(re.findall(r'persist_file\(\s*"([\w_]+)"', text))
    return sorted(ks)


def main():
    server = (ROOT / "server.py").read_text(encoding="utf-8")
    r = routes(server)
    lines = [
        "# GiveLife dependency map",
        "",
        "Generated by `scripts/dependency_map.py`; do not edit by hand.",
        "",
    ]
    lines += [
        "## Python modules (imports inside this repo)",
        "",
        "| Module | Imports | Imported by |",
        "|---|---|---|",
    ]
    graph = {p.stem: imports(p) for p in PY}
    for name, deps in graph.items():
        used_by = sorted(k for k, v in graph.items() if name in v)
        lines.append(f"| {name} | {', '.join(deps) or '-'} | {', '.join(used_by) or '-'} |")
    lines += ["", "## Background threads (a failure in one must not affect the others)", ""]
    for p in PY:
        t = threads(p)
        if t:
            lines.append(f"- **{p.stem}**: " + ", ".join(t))
    lines += ["", "## Persisted state keys (database store) by module", ""]
    for p in PY:
        k = keys(p)
        if k:
            lines.append(f"- **{p.stem}**: " + ", ".join(k))
    lines += ["", f"## HTTP routes ({len(r['GET'])} GET, {len(r['POST'])} POST)", ""]
    lines.append("GET: " + ", ".join(sorted(r["GET"])))
    lines.append("")
    lines.append("POST: " + ", ".join(sorted(r["POST"])))
    lines += ["", "## Browser files and the endpoints they call", ""]
    for js in sorted(ROOT.glob("*.js")):
        text = js.read_text(encoding="utf-8")
        eps = sorted(set(re.findall(r"""(?:fetch|post|api)\(\s*['"`](/[\w/\-.]*)""", text)))
        lines.append(f"- **{js.name}**: " + (", ".join(eps) or "-"))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT), len(graph), "modules")


if __name__ == "__main__":
    sys.exit(main())
